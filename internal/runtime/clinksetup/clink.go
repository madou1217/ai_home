// Package clinksetup 安装/维护 Clink 的 aih 补全脚本。
//
// cmd.exe 没有可编程补全接口；Clink 是 cmd 的 readline 层，提供 Lua 生成器。
// 本包只负责检测 Clink、写 aih.lua、报告状态；真正的候选仍由 aih __complete 提供。
package clinksetup

import (
	"context"
	_ "embed"
	"errors"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"runtime"
	"strings"
	"time"

	"github.com/madou1217/ai_home/internal/runtime/platform"
)

const (
	// ScriptName 是 Clink 状态目录里的补全脚本名。
	ScriptName = "aih.lua"
	// ScriptMarker 用于识别受管脚本。
	ScriptMarker = "-- aih:clink v1"
)

// ErrNotAvailable 表示本机没有找到 Clink。
var ErrNotAvailable = errors.New("未找到 Clink（请先安装 Clink）")

//go:embed aih.lua
var luaBody string

// Info 是 Clink 安装事实。
type Info struct {
	Exe         string
	Version     string
	StateDir    string
	ScriptsDirs []string
}

// ScriptDir 返回应写入 aih.lua 的目录：状态目录优先（Clink 一定加载）。
func (info Info) ScriptDir() string {
	if strings.TrimSpace(info.StateDir) != "" {
		return strings.TrimSpace(info.StateDir)
	}
	for _, dir := range info.ScriptsDirs {
		if strings.TrimSpace(dir) != "" {
			return strings.TrimSpace(dir)
		}
	}
	return ""
}

// Status 是 CLI/doctor 使用的状态快照。
type Status struct {
	Available  bool   `json:"available"`
	Exe        string `json:"exe,omitempty"`
	Version    string `json:"version,omitempty"`
	ScriptDir  string `json:"scriptDir,omitempty"`
	ScriptPath string `json:"scriptPath,omitempty"`
	Installed  bool   `json:"installed"`
	UpToDate   bool   `json:"upToDate"`
	Reason     string `json:"reason,omitempty"`
}

func lookup(env func(string) string, name string) string {
	if env == nil {
		return ""
	}
	return strings.TrimSpace(env(name))
}

func isFile(path string) bool {
	info, err := os.Stat(path)
	return err == nil && !info.IsDir()
}

func dedupe(values []string) []string {
	seen := make(map[string]struct{}, len(values))
	result := make([]string, 0, len(values))
	for _, value := range values {
		key := strings.ToLower(value)
		if _, exists := seen[key]; exists {
			continue
		}
		seen[key] = struct{}{}
		result = append(result, value)
	}
	return result
}

func candidatePaths(env func(string) string) []string {
	paths := make([]string, 0, 8)
	if explicit := lookup(env, "CLINK_EXE"); explicit != "" {
		paths = append(paths, explicit)
	}
	for _, name := range []string{"clink_x64.exe", "clink.exe", "clink_x64", "clink"} {
		if resolved, err := exec.LookPath(name); err == nil {
			paths = append(paths, resolved)
		}
	}
	local := lookup(env, "LOCALAPPDATA")
	if local != "" {
		paths = append(paths,
			filepath.Join(local, "clink", "clink_x64.exe"),
			filepath.Join(local, "Programs", "clink", "clink_x64.exe"),
		)
	}
	for _, base := range []string{lookup(env, "ProgramFiles(x86)"), lookup(env, "ProgramFiles")} {
		if base != "" {
			paths = append(paths, filepath.Join(base, "clink", "clink_x64.exe"))
		}
	}
	return dedupe(paths)
}

// Detect 找到 Clink 并解析 clink info 的 state/scripts 目录。
func Detect(env func(string) string) (Info, bool) {
	if runtime.GOOS != "windows" {
		return Info{}, false
	}
	for _, candidate := range candidatePaths(env) {
		if !isFile(candidate) {
			continue
		}
		if info, ok := probe(candidate, env); ok {
			return info, true
		}
	}
	return Info{}, false
}

func probe(exe string, env func(string) string) (Info, bool) {
	ctx, cancel := context.WithTimeout(context.Background(), 5*time.Second)
	defer cancel()
	command := exec.CommandContext(ctx, exe, "info")
	command.Env = os.Environ()
	output, err := command.Output()
	if err != nil && len(output) == 0 {
		return Info{}, false
	}
	info := Info{Exe: exe}
	for _, line := range strings.Split(string(output), "\n") {
		key, value, found := strings.Cut(line, ":")
		if !found {
			continue
		}
		key = strings.TrimSpace(key)
		value = strings.TrimSpace(value)
		switch key {
		case "version":
			info.Version = value
		case "state":
			info.StateDir = value
		case "scripts":
			for _, dir := range strings.Split(value, ";") {
				if dir = strings.TrimSpace(dir); dir != "" {
					info.ScriptsDirs = append(info.ScriptsDirs, dir)
				}
			}
		}
	}
	if info.StateDir == "" {
		if local := lookup(env, "LOCALAPPDATA"); local != "" {
			info.StateDir = filepath.Join(local, "clink")
		}
	}
	if info.StateDir == "" && len(info.ScriptsDirs) == 0 {
		return Info{}, false
	}
	return info, true
}

// FallbackDir 是 Clink 不在时仍可清理脚本的用户目录。
func FallbackDir(env func(string) string) string {
	if local := lookup(env, "LOCALAPPDATA"); local != "" {
		return filepath.Join(local, "clink")
	}
	return ""
}

// LuaScript 生成受管的 Clink 补全脚本；aihBin 是执行 __complete 的路径。
func LuaScript(aihBin string) string {
	bin := strings.TrimSpace(aihBin)
	if bin == "" {
		bin = "aih"
	}
	var builder strings.Builder
	builder.WriteString(ScriptMarker)
	builder.WriteString("\n")
	builder.WriteString("-- Generated by aih shell apply --shell cmd; remove with aih shell remove --shell cmd.\n")
	builder.WriteString("-- Candidates come from aih __complete. Plain values are used by default because\n")
	builder.WriteString("-- cmd consoles often use codepage 936. Set AIH_CLINK_DESCRIPTIONS=1 with UTF-8 for descriptions.\n")
	builder.WriteString("local aih_bin = [[")
	builder.WriteString(bin)
	builder.WriteString("]]\n")
	builder.WriteString(strings.TrimLeft(luaBody, "\r\n"))
	return builder.String()
}

// Apply 写入 aih.lua；返回路径、是否变化、Clink 信息。
func Apply(aihBin string, env func(string) string) (string, bool, Info, error) {
	info, ok := Detect(env)
	if !ok {
		return "", false, Info{}, ErrNotAvailable
	}
	dir := info.ScriptDir()
	if dir == "" {
		return "", false, info, errors.New("Clink 的脚本目录不可用")
	}
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return "", false, info, err
	}
	path := filepath.Join(dir, ScriptName)
	desired := []byte(LuaScript(aihBin))
	if current, err := os.ReadFile(path); err == nil && string(current) == string(desired) {
		return path, false, info, nil
	}
	temp := path + fmt.Sprintf(".tmp-%d", os.Getpid())
	if err := os.WriteFile(temp, desired, 0o644); err != nil {
		return "", false, info, err
	}
	if err := os.Rename(temp, path); err != nil {
		_ = os.Remove(path)
		if renameErr := os.Rename(temp, path); renameErr != nil {
			_ = os.Remove(temp)
			return "", false, info, renameErr
		}
	}
	return path, true, info, nil
}

// Remove 删除 aih.lua；Clink 不在时回落到默认状态目录。
func Remove(env func(string) string) (string, bool, error) {
	info, ok := Detect(env)
	dir := ""
	if ok {
		dir = info.ScriptDir()
	}
	if dir == "" {
		dir = FallbackDir(env)
	}
	if dir == "" {
		return "", false, nil
	}
	path := filepath.Join(dir, ScriptName)
	if err := os.Remove(path); err != nil {
		if os.IsNotExist(err) {
			return path, false, nil
		}
		return path, false, err
	}
	return path, true, nil
}

// GetStatus 返回当前 Clink 与脚本状态。
func GetStatus(aihBin string, env func(string) string) Status {
	info, ok := Detect(env)
	if !ok {
		return Status{Available: false, Reason: "clink_not_found"}
	}
	path := filepath.Join(info.ScriptDir(), ScriptName)
	status := Status{
		Available:  true,
		Exe:        info.Exe,
		Version:    info.Version,
		ScriptDir:  info.ScriptDir(),
		ScriptPath: path,
	}
	current, err := os.ReadFile(path)
	if err != nil {
		status.Reason = "script_missing"
		return status
	}
	status.Installed = true
	status.UpToDate = string(current) == LuaScript(aihBin)
	if !status.UpToDate {
		status.Reason = "script_outdated"
	}
	return status
}

// ExecutableAvailable 判断 aihBin 是否是 Windows 可执行文件。
func ExecutableAvailable(path string) bool {
	return platform.IsExecutable(strings.TrimSpace(path))
}

func parseHookDocument(snapshot configsnapshot.Snapshot) (map[string]any, error) {
	if !snapshot.Exists {
		return map[string]any{}, nil
	}
	value, err := jsondocument.Object(snapshot.Content)
	if err != nil {
		return nil, errors.New("hook_config_invalid")
	}
	if hooks, exists := value["hooks"]; exists {
		object, ok := hooks.(map[string]any)
		if !ok {
			return nil, errors.New("hook_config_schema_conflict")
		}
		for _, event := range object {
			if _, ok := event.([]any); !ok {
				return nil, errors.New("hook_config_schema_conflict")
			}
		}
	}
	return value, nil
}
func readHookDocument(target string) (map[string]any, error) {
	snapshot, err := configsnapshot.Read(target)
	if err != nil {
		return nil, err
	}
	return parseHookDocument(snapshot)
}

// The signature detects user edits to generated plugins. Legacy files are
// adopted only when every byte matches the known template and its literal URL.
//
//go:embed templates/opencode-node-v1.js.txt
var legacyNodeOpenCodeTemplate string

const openCodeOwnershipPrefix = "// aih-owned-sha256:"

func signedOpenCodeSource(body string) string {
	sum := sha256.Sum256([]byte(body))
	return openCodeOwnershipPrefix + hex.EncodeToString(sum[:]) + "\n" + body
}
func ownedOpenCodeSource(raw []byte) bool {
	text := string(raw)
	if strings.HasPrefix(text, openCodeOwnershipPrefix) {
		line, body, ok := strings.Cut(text, "\n")
		if !ok {
			return false
		}
		sum := sha256.Sum256([]byte(body))
		return line == openCodeOwnershipPrefix+hex.EncodeToString(sum[:])
	}
	const prefix = "const AIH_RECEIVER_URL = "
	start := strings.Index(text, prefix)
	if start < 0 {
		return false
	}
	rest := text[start+len(prefix):]
	end := strings.Index(rest, ";\n")
	if end < 0 {
		return false
	}
	var url string
	if json.Unmarshal([]byte(rest[:end]), &url) != nil {
		return false
	}
	literal, _ := json.Marshal(url)
	expected := strings.ReplaceAll(openCodePluginTemplate, "__AIH_RECEIVER_URL_LITERAL__", string(literal))
	if bytes.Equal(raw, []byte(expected)) {
		return true
	}
	legacy := strings.ReplaceAll(legacyNodeOpenCodeTemplate, "__AIH_RECEIVER_URL_LITERAL__", string(literal))
	return bytes.Equal(raw, []byte(legacy))
}
func agyHookOwned(value any, provider string, allowed ...string) bool {
	record, ok := value.(map[string]any)
	if !ok {
		return false
	}
	saw := false
	for key, value := range record {
		if key == "enabled" {
			if _, ok := value.(bool); !ok {
				return false
			}
			continue
		}
		if !agyKnownEvent(key) {
			continue
		}
		events, ok := value.([]any)
		if !ok {
			return false
		}
		for _, event := range events {
			item, ok := event.(map[string]any)
			if !ok {
				return false
			}
			if command, ok := item["command"].(string); ok {
				if !isManagedCommandString(command, provider, allowed...) {
					return false
				}
				saw = true
				continue
			}
			hooks, ok := item["hooks"].([]any)
			if !ok {
				return false
			}
			for _, hook := range hooks {
				handler, ok := hook.(map[string]any)
				if !ok {
					return false
				}
				command, _ := handler["command"].(string)
				if !isManagedCommandString(command, provider, allowed...) {
					return false
				}
				saw = true
			}
		}
	}
	return saw
}

// splitHookCommand handles the simple quoted argv generated by AIH. Shell
// operators outside quotes are rejected; no evaluation or execution occurs.
func splitHookCommand(text string) ([]string, bool) {
	var fields []string
	var word strings.Builder
	quote := rune(0)
	escaped := false
	started := false
	for _, r := range text {
		if escaped {
			word.WriteRune(r)
			escaped = false
			started = true
			continue
		}
		if quote == '\'' {
			if r == quote {
				quote = 0
			} else {
				word.WriteRune(r)
			}
			started = true
			continue
		}
		if quote == '"' {
			if r == quote {
				quote = 0
			} else {
				word.WriteRune(r)
			}
			started = true
			continue
		}
		switch r {
		case '\'', '"':
			quote = r
			started = true
		case '\\':
			escaped = true
		case ' ', '\t':
			if started {
				fields = append(fields, word.String())
				word.Reset()
				started = false
			}
		case ';', '|', '&', '>', '<', '\n', '\r', '`':
			return nil, false
		default:
			word.WriteRune(r)
			started = true
		}
	}
	if quote != 0 || escaped {
		return nil, false
	}
	if started {
		fields = append(fields, word.String())
	}
	return fields, true
}

func readJSONObjectSafe(target string) map[string]any {
	raw, err := os.ReadFile(target)
	if err != nil {
		return map[string]any{}
	}
	out, decodeErr := jsondocument.Object(raw)
	if decodeErr != nil || out == nil {
		return map[string]any{}
	}
	return out
}

func cloneJSONMap(src map[string]any) map[string]any {
	out := make(map[string]any, len(src))
	for key, value := range src {
		out[key] = cloneJSONValue(value)
	}
	return out
}
func cloneJSONValue(value any) any {
	switch v := value.(type) {
	case map[string]any:
		return cloneJSONMap(v)
	case []any:
		out := make([]any, len(v))
		for i, item := range v {
			out[i] = cloneJSONValue(item)
		}
		return out
	default:
		return value
	}
}

func agyKnownEvent(key string) bool {
	switch key {
	case "PreInvocation", "PostInvocation", "Stop", "PreToolUse", "PostToolUse":
		return true
	}
	return false
}

'use strict';

const path = require('path');
const nodeFs = require('node:fs');
const { spawnSync } = require('node:child_process');
const { BaseMultiplexerDriver } = require('./base-driver');
const { MULTIPLEXER_TYPE } = require('../types');
const { TMUX_SAFE_RENDER_ENV_KEYS } = require('../tmux-session-env');

const DISABLE_ENV = 'AIH_NO_PERSIST';
const RUN_EXIT_MARKER = '__AIH_RUN_EXIT:';
const RUN_SESSION_NAME = 'run';
const PSMUX_WINGET_PACKAGE_ID = 'marlocarlo.psmux';

const WINDOWS_TMUX_CANDIDATES = [
  { command: 'psmux', viaShell: false },
  { command: 'tmux', viaShell: false },
  { command: 'C:\\msys64\\usr\\bin\\tmux.exe', viaShell: false },
  { command: 'C:\\cygwin64\\bin\\tmux.exe', viaShell: false }
];


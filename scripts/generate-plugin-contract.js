'use strict';

// 插件线合同的唯一来源是 contracts/plugins/contract.json；Node、Go、TS 三端的常量与 DTO 都由这里生成。
// `--check` 只比对不写入，测试据此保证生成物不漂移。

const fs = require('node:fs');
const path = require('node:path');

const root = path.resolve(__dirname, '..');
const contract = JSON.parse(fs.readFileSync(path.join(root, 'contracts/plugins/contract.json'), 'utf8'));
const schema = fs.readFileSync(path.join(root, 'contracts/plugins/manifest.schema.json'), 'utf8');
const goTypes = { string: 'string', uint32: 'uint32', int64: 'int64', json: 'json.RawMessage' };
const tsTypes = { string: 'string', uint32: 'number', int64: 'number', json: 'unknown' };
const capitalize = (name) => name[0].toUpperCase() + name.slice(1);
const goName = (name) => capitalize(name).replace(/Id$/, 'ID');
const goIdentifier = (value) => value.split(/[^a-zA-Z0-9]+/).filter(Boolean).map(capitalize).join('');

// 按 gofmt 的规则对齐（标识符列补空格到最长者 + 1），生成物不依赖本机 gofmt 也能通过 gofmt -l。
function alignedBlock(rows) {
  const widths = [];
  for (const row of rows) row.slice(0, -1).forEach((cell, index) => { widths[index] = Math.max(widths[index] || 0, cell.length); });
  return rows.map((row) => '\t' + row.map((cell, index) => (index < row.length - 1 ? cell.padEnd(widths[index] + 1) : cell)).join('')).join('\n') + '\n';
}

function renderGo() {
  let go = '// Code generated by scripts/generate-plugin-contract.js; DO NOT EDIT.\npackage plugincontract\n\nimport "encoding/json"\n\n';
  go += 'const ProtocolVersion uint32 = ' + contract.protocolVersion + '\n';
  go += 'const MinProtocolVersion uint32 = ' + contract.supportedProtocolVersions.min + '\n';
  go += 'const MaxProtocolVersion uint32 = ' + contract.supportedProtocolVersions.max + '\n';
  for (const [name, value] of Object.entries(contract.limits)) {
    go += 'const Max' + capitalize(name) + ' = ' + value + '\n';
  }
  go += '\nconst (\n' + alignedBlock(contract.messageKinds.map((kind) => ['Kind' + goIdentifier(kind), '= "' + kind + '"'])) + ')\n';
  go += '\nconst (\n' + alignedBlock(contract.errorCodes.map((code) => ['Code' + goIdentifier(code.replace(/^plugin_/, '')), '= "' + code + '"'])) + ')\n';
  for (const [name, fields] of Object.entries(contract.wireTypes)) {
    const rows = Object.entries(fields).map(([raw, type]) => {
      const optional = raw.endsWith('?');
      const field = optional ? raw.slice(0, -1) : raw;
      const goType = goTypes[type] || (optional ? '*' : '') + type;
      return [goName(field), goType, '`json:"' + field + (optional ? ',omitempty' : '') + '"`'];
    });
    go += '\ntype ' + name + ' struct {\n' + alignedBlock(rows) + '}\n';
  }
  return go;
}

function renderTs() {
  let ts = '// Generated from contracts/plugins/contract.json; DO NOT EDIT.\n';
  ts += '\nexport type MessageKind = ' + contract.messageKinds.map((kind) => JSON.stringify(kind)).join(' | ') + ';\n';
  ts += '\nexport type ErrorCode = ' + contract.errorCodes.map((code) => JSON.stringify(code)).join(' | ') + ';\n';
  for (const [name, fields] of Object.entries(contract.wireTypes)) {
    ts += '\nexport interface ' + name + ' {\n';
    for (const [raw, type] of Object.entries(fields)) ts += '  ' + raw + ': ' + (tsTypes[type] || type) + ';\n';
    ts += '}\n';
  }
  return ts;
}

function outputs() {
  return new Map([
    ['lib/plugins/sdk/contract.generated.json', JSON.stringify(contract, null, 2) + '\n'],
    ['lib/plugins/sdk/manifest.schema.generated.json', schema],
    ['lib/plugins/sdk/wire.generated.d.ts', renderTs()],
    ['contracts/plugins/contract.generated.go', renderGo()]
  ]);
}

function run({ check = false } = {}) {
  const stale = [];
  for (const [relative, content] of outputs()) {
    const file = path.join(root, relative);
    if (check) {
      if (!fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== content) stale.push(relative);
    } else {
      fs.mkdirSync(path.dirname(file), { recursive: true });
      fs.writeFileSync(file, content);
    }
  }
  return stale;
}

if (require.main === module) {
  const check = process.argv.includes('--check');
  const stale = run({ check });
  if (stale.length) throw new Error('plugin_contract_outdated:' + stale.join(','));
  process.stdout.write(check ? 'Plugin contract is current.\n' : 'Plugin contract generated.\n');
}

module.exports = { run };
